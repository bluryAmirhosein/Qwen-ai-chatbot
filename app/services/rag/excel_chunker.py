import io
from datetime import date, datetime, time
from typing import Any, Iterable

from openpyxl import load_workbook


class ExcelChunker:
    """Turns an .xlsx workbook into row-level chunks for RAG retrieval.

    Every non-empty row becomes one chunk of "column: value" pairs, prefixed
    with the sheet name and the real Excel row number. Rows whose formatted
    text exceeds `max_chars_per_chunk` are split into several parts; each
    part repeats the row's first column (usually an identifier) so that the
    part stays attributable to its row.

    Notes:
    - The first non-empty row of every sheet is treated as the header.
    - Formula cells are read as their cached values (data_only=True), so a
      file that was generated by a library and never opened in Excel may
      contain empty values for formulas.
    - Empty cells are skipped to keep chunks short.
    """

    def __init__(self, max_chars_per_chunk: int = 1200):
        if max_chars_per_chunk < 200:
            raise ValueError("max_chars_per_chunk must be at least 200")
        self._max_chars = max_chars_per_chunk

    def split(self, data: bytes) -> list[str]:
        workbook = load_workbook(io.BytesIO(data), read_only=True, data_only=True)
        try:
            chunks: list[str] = []
            for sheet in workbook.worksheets:
                chunks.extend(self._split_sheet(sheet.title, sheet.iter_rows(values_only=True)))
            return chunks
        finally:
            workbook.close()

    def _split_sheet(self, sheet_name: str, rows: Iterable[tuple]) -> list[str]:
        chunks: list[str] = []
        headers: list[str] | None = None

        for row_number, row in enumerate(rows, start=1):
            if headers is None:
                if any(self._is_filled(cell) for cell in row):
                    headers = self._build_headers(row)
                continue

            pairs = self._row_pairs(headers, row)
            if pairs:
                chunks.extend(self._format_row(sheet_name, row_number, pairs))

        return chunks

    @staticmethod
    def _build_headers(row: tuple) -> list[str]:
        headers: list[str] = []
        seen: dict[str, int] = {}
        for index, cell in enumerate(row, start=1):
            name = str(cell).strip() if cell is not None and str(cell).strip() else f"Column_{index}"
            if name in seen:
                seen[name] += 1
                name = f"{name}_{seen[name]}"
            else:
                seen[name] = 1
            headers.append(name)
        return headers

    def _row_pairs(self, headers: list[str], row: tuple) -> list[tuple[str, str]]:
        pairs: list[tuple[str, str]] = []
        for index, cell in enumerate(row):
            if not self._is_filled(cell):
                continue
            name = headers[index] if index < len(headers) else f"Column_{index + 1}"
            pairs.append((name, self._format_value(cell)))
        return pairs

    def _format_row(self, sheet: str, row_number: int, pairs: list[tuple[str, str]]) -> list[str]:
        prefix = f"[Sheet: {sheet} | Row {row_number}]"
        line = " | ".join(f"{k}: {v}" for k, v in pairs)
        full = f"{prefix}\n{line}"
        if len(full) <= self._max_chars:
            return [full]

        key_pair = pairs[0]
        key_text = f"{key_pair[0]}: {key_pair[1]}"
        groups: list[list[tuple[str, str]]] = []
        current: list[tuple[str, str]] = []
        current_len = 0
        budget = self._max_chars - len(prefix) - len(key_text) - 40

        for pair in pairs:
            pair_text = f"{pair[0]}: {pair[1]}"
            if current and current_len + len(pair_text) + 3 > budget:
                groups.append(current)
                current, current_len = [], 0
            current.append(pair)
            current_len += len(pair_text) + 3
        if current:
            groups.append(current)

        total = len(groups)
        parts: list[str] = []
        for part_index, group in enumerate(groups, start=1):
            part_pairs = group if group[0] == key_pair else [key_pair, *group]
            body = " | ".join(f"{k}: {v}" for k, v in part_pairs)
            parts.append(f"[Sheet: {sheet} | Row {row_number} | Part {part_index}/{total}]\n{body}")
        return parts

    @staticmethod
    def _is_filled(value: Any) -> bool:
        return value is not None and str(value).strip() != ""

    @staticmethod
    def _format_value(value: Any) -> str:
        if isinstance(value, datetime):
            if value.time() == time(0, 0):
                return value.date().isoformat()
            return value.isoformat(sep=" ", timespec="seconds")
        if isinstance(value, date):
            return value.isoformat()
        if isinstance(value, float) and value.is_integer():
            return str(int(value))
        if isinstance(value, bool):
            return "true" if value else "false"
        return " ".join(str(value).split())